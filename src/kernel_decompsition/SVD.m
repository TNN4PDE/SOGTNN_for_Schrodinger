%% ------------------ 积分节点生成 ------------------
function [x_all, w_all] = generate_flexible_quadrature(node_nums, block_nums, ratios, a, b)
% 通用高斯积分节点生成器
% 输入:
%   node_nums  - 每段的小区间 Gauss 点数 (e.g. [8,6,0,12])
%   block_nums - 每段的小区间个数 (e.g. [15,80,0,5])
%   ratios     - 每段所占比例 (e.g. [1,2,1,0.5])
%   a, b       - 区间范围 (e.g. -1, 1)
% 输出:
%   x_all, w_all - 所有积分点与权重 (列向量)

    assert(length(node_nums) == length(block_nums) && length(node_nums) == length(ratios), ...
        'node_nums, block_nums, ratios 长度必须一致');
    K = length(node_nums);

    % 归一化比例，计算各段边界
    ratios = ratios / sum(ratios);
    L = b - a;
    boundaries = a + [0, cumsum(ratios)] * L;

    x_all = [];
    w_all = [];

    for i = 1:K
        N = node_nums(i);
        M = block_nums(i);

        if N == 0 || M == 0
            continue;  % 跳过此段
        end

        [xi, wi] = get_gauss_legendre(N);  % 获取 Gauss 节点

        seg_a = boundaries(i);
        seg_b = boundaries(i+1);
        sub_bounds = linspace(seg_a, seg_b, M + 1);

        for j = 1:M
            left = sub_bounds(j);
            right = sub_bounds(j+1);
            % 映射到该小区间
            x_mapped = ((xi + 1) / 2) * (right - left) + left;
            w_mapped = (wi / 2) * (right - left);
            x_all = [x_all; x_mapped(:)];
            w_all = [w_all; w_mapped(:)];
        end
    end
end

